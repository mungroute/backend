SELECT profile.user_id,
       profile.dog_name,
       profile.breed,
       CURRENT_DATE - make_interval(years => COALESCE(profile.age_years, 0)),
       profile.profile_image_url,
       profile.temperament_tags,
       true
FROM meet_profile profile
WHERE NOT EXISTS (
    SELECT 1 FROM dog_profile dog WHERE dog.user_id = profile.user_id
);

